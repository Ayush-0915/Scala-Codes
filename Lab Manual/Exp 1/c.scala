object DataTypesDemo {
  def main(args: Array[String]): Unit = {

    val intValue: Int = 100
    val longValue: Long = 100000L
    val doubleValue: Double = 25.75
    val floatValue: Float = 12.5f
    val charValue: Char = 'A'
    val stringValue: String = "Scala Programming"
    val booleanValue: Boolean = true

    println("Int: " + intValue)
    println("Long: " + longValue)
    println("Double: " + doubleValue)
    println("Float: " + floatValue)
    println("Char: " + charValue)
    println("String: " + stringValue)
    println("Boolean: " + booleanValue)
  }
}